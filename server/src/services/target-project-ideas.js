import { nanoid } from 'nanoid'
import { badRequest, forbidden, notFound } from '../domain/errors.js'

/**
 * Hedef Projeler — a lightweight idea board. Designers and the team leader
 * jot down a book concept before it becomes a real project; often just a
 * link (and optionally a photo) someone spotted on Instagram. See
 * migration 036__target_project_ideas.sql, image support in 037, and the
 * multi-link / gallery / notes-log detail view in
 * 042__target_project_idea_details.sql.
 *
 * The card grid (list()) only needs the cover image and links — the
 * gallery and notes log are fetched together via getDetail() when someone
 * opens an idea's detail view, so the list stays a single cheap query.
 */

const COLUMNS = `id, name, links, image_url, image_updated_at, created_by, created_by_name, created_at`
const MAX_LINKS = 10

function normalizeLinks(links) {
  if (!Array.isArray(links)) return []
  return links.map((l) => (l ?? '').trim()).filter(Boolean).slice(0, MAX_LINKS)
}

export async function list(pool) {
  const { rows } = await pool.query(
    `SELECT ${COLUMNS} FROM target_project_ideas ORDER BY created_at DESC`,
  )
  return rows
}

export async function create(client, { name, links }, actor) {
  const trimmedName = (name ?? '').trim()
  if (!trimmedName) badRequest('İsim boş olamaz.')
  const { rows } = await client.query(
    `INSERT INTO target_project_ideas (id, name, links, created_by, created_by_name)
     VALUES ($1, $2, $3, $4, $5)
     RETURNING ${COLUMNS}`,
    [
      `tpi-${nanoid(16)}`,
      trimmedName,
      normalizeLinks(links),
      actor.id,
      actor.name,
    ],
  )
  return rows[0]
}

/**
 * team_leader can modify (delete, or change the image of) any idea;
 * anyone else only the one they added. Shared by remove() and the image
 * routes so an unauthorized caller is rejected before any file I/O happens.
 */
export async function assertCanModify(pool, id, actor) {
  const { rows } = await pool.query(
    `SELECT created_by FROM target_project_ideas WHERE id = $1`,
    [id],
  )
  if (!rows[0]) notFound('Kayıt bulunamadı.')
  if (actor.role !== 'team_leader' && rows[0].created_by !== actor.id) {
    forbidden('Bu kaydı yalnızca ekleyen kişi veya takım lideri düzenleyebilir.')
  }
}

export async function update(pool, id, actor, patch) {
  await assertCanModify(pool, id, actor)

  const sets = []
  const values = []
  let i = 1

  if (patch.name !== undefined) {
    const trimmed = (patch.name ?? '').trim()
    if (!trimmed) badRequest('İsim boş olamaz.')
    sets.push(`name = $${i++}`)
    values.push(trimmed)
  }
  if (patch.links !== undefined) {
    sets.push(`links = $${i++}`)
    values.push(normalizeLinks(patch.links))
  }

  if (!sets.length) badRequest('Güncellenecek alan yok.')

  values.push(id)
  const { rows } = await pool.query(
    `UPDATE target_project_ideas SET ${sets.join(', ')} WHERE id = $${i} RETURNING ${COLUMNS}`,
    values,
  )
  if (!rows[0]) notFound('Kayıt bulunamadı.')
  return rows[0]
}

export async function remove(pool, id, actor) {
  await assertCanModify(pool, id, actor)
  await pool.query(`DELETE FROM target_project_ideas WHERE id = $1`, [id])
  return true
}

export async function setImage(pool, id, imageUrl) {
  const { rows } = await pool.query(
    `UPDATE target_project_ideas SET image_url = $2, image_updated_at = NOW()
      WHERE id = $1 RETURNING ${COLUMNS}`,
    [id, imageUrl],
  )
  if (!rows[0]) notFound('Kayıt bulunamadı.')
  return rows[0]
}

export async function clearImage(pool, id) {
  const { rows } = await pool.query(
    `UPDATE target_project_ideas SET image_url = NULL, image_updated_at = NULL
      WHERE id = $1 RETURNING ${COLUMNS}`,
    [id],
  )
  if (!rows[0]) notFound('Kayıt bulunamadı.')
  return rows[0]
}

// ─── detail view: cover + links come from the row above; gallery and
// notes log live in their own child tables ──────────────────────────────

export async function getDetail(pool, id) {
  const { rows } = await pool.query(`SELECT ${COLUMNS} FROM target_project_ideas WHERE id = $1`, [id])
  if (!rows[0]) notFound('Kayıt bulunamadı.')
  const [images, notes] = await Promise.all([listImages(pool, id), listNotes(pool, id)])
  return { ...rows[0], images, notes }
}

// ─── gallery — extra photos beyond the cover. Callers (routes) gate with
// assertCanModify BEFORE reading a file off the wire, same as the cover
// image route; these functions trust that's already been done ──────────

export async function listImages(pool, ideaId) {
  const { rows } = await pool.query(
    `SELECT id, idea_id, image_url, created_by, created_at
       FROM target_project_idea_images WHERE idea_id = $1 ORDER BY created_at ASC`,
    [ideaId],
  )
  return rows
}

/** `imageId` is generated by the caller — it's baked into the on-disk path before this runs. */
export async function addImage(pool, ideaId, imageId, imageUrl, actor) {
  const { rows } = await pool.query(
    `INSERT INTO target_project_idea_images (id, idea_id, image_url, created_by)
     VALUES ($1, $2, $3, $4)
     RETURNING id, idea_id, image_url, created_by, created_at`,
    [imageId, ideaId, imageUrl, actor.id],
  )
  return rows[0]
}

export async function removeImage(pool, ideaId, imageId) {
  const { rows } = await pool.query(
    `DELETE FROM target_project_idea_images WHERE id = $1 AND idea_id = $2 RETURNING id`,
    [imageId, ideaId],
  )
  if (!rows[0]) notFound('Görsel bulunamadı.')
  return true
}

// ─── notes log — a timestamped, multi-author log that replaced the old
// single `notes` textarea. Anyone who can add an idea can add a note;
// removing one is gated like any other record: team_leader, or the
// note's own author ───────────────────────────────────────────────────

export async function listNotes(pool, ideaId) {
  const { rows } = await pool.query(
    `SELECT id, idea_id, body, created_by, created_by_name, created_at
       FROM target_project_idea_notes WHERE idea_id = $1 ORDER BY created_at ASC`,
    [ideaId],
  )
  return rows
}

export async function addNote(pool, ideaId, body, actor) {
  const trimmed = (body ?? '').trim()
  if (!trimmed) badRequest('Not boş olamaz.')
  const { rows: ideaRows } = await pool.query(`SELECT id FROM target_project_ideas WHERE id = $1`, [ideaId])
  if (!ideaRows[0]) notFound('Kayıt bulunamadı.')
  const { rows } = await pool.query(
    `INSERT INTO target_project_idea_notes (id, idea_id, body, created_by, created_by_name)
     VALUES ($1, $2, $3, $4, $5)
     RETURNING id, idea_id, body, created_by, created_by_name, created_at`,
    [`tpin-${nanoid(16)}`, ideaId, trimmed, actor.id, actor.name],
  )
  return rows[0]
}

export async function removeNote(pool, ideaId, noteId, actor) {
  const { rows: noteRows } = await pool.query(
    `SELECT created_by FROM target_project_idea_notes WHERE id = $1 AND idea_id = $2`,
    [noteId, ideaId],
  )
  if (!noteRows[0]) notFound('Not bulunamadı.')
  if (actor.role !== 'team_leader' && noteRows[0].created_by !== actor.id) {
    forbidden('Bu notu yalnızca ekleyen kişi veya takım lideri silebilir.')
  }
  await pool.query(`DELETE FROM target_project_idea_notes WHERE id = $1`, [noteId])
  return true
}
